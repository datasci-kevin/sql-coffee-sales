-- =============================================================================
-- Question 7:
-- What percentage of total profit does each product contribute?
-- =============================================================================

WITH ProductProfit AS (
    SELECT
        p.product_id,
        SUM(o.quantity * p.profit) AS product_profit

    FROM gold.fact_orders AS o

    LEFT JOIN gold.dim_products AS p
        ON o.product_key = p.product_key

    GROUP BY
        p.product_id
),

TotalProductProfit AS (
    SELECT
        product_id,
        product_profit,

        SUM(product_profit) OVER () AS total_profit

    FROM ProductProfit
)

SELECT
    product_id,
    product_profit,
    total_profit,

    ROUND(
        100.0 * product_profit
        / NULLIF(total_profit, 0),
        2
    ) AS profit_contribution_percentage

FROM TotalProductProfit
ORDER BY
    profit_contribution_percentage DESC;

-- =============================================================================
-- Question 8:
-- What percentage of total sales is generated by the top 10 customers?
-- =============================================================================

WITH CustomerSales AS (
    SELECT
        c.customer_id,
        c.customer_name,
        SUM(o.sales) AS customer_sales

    FROM gold.fact_orders AS o

    LEFT JOIN gold.dim_customers AS c
        ON o.customer_key = c.customer_key

    GROUP BY
        c.customer_id,
        c.customer_name
),

RankedCustomers AS (
    SELECT
        customer_id,
        customer_name,
        customer_sales,

        ROW_NUMBER() OVER (
            ORDER BY customer_sales DESC
        ) AS customer_rank

    FROM CustomerSales
),

SalesTotals AS (
    SELECT
        SUM(
            CASE
                WHEN customer_rank <= 10 THEN customer_sales
                ELSE 0
            END
        ) AS top_10_customer_sales,

        SUM(customer_sales) AS total_sales

    FROM RankedCustomers
)

SELECT
    top_10_customer_sales,
    total_sales,

    ROUND(
        100.0 * top_10_customer_sales
        / NULLIF(total_sales, 0),
        2
    ) AS top_10_sales_contribution_percentage

FROM SalesTotals;
