/*
===============================================================================
09. PART-TO-WHOLE ANALYSIS
===============================================================================

Purpose:
    Analyze how individual categories contribute to overall business results.

Business Questions:
    1. What percentage of total sales does each coffee type contribute?
    2. What percentage of total sales does each roast type contribute?
    3. What percentage of total sales does each size category contribute?
    4. What percentage of total sales does each country contribute?
    5. What percentage of total sales comes from loyalty vs non-loyalty customers?
    6. What percentage of total quantity sold belongs to each coffee type?
    7. What percentage of total profit does each product contribute?
    8. What percentage of sales is generated by the top 10 customers?
*/


-- =============================================================================
-- Question 1:
-- What percentage of total sales does each coffee type contribute?
-- =============================================================================

WITH CoffeeTypeSales AS (
    SELECT
        p.coffee_type,
        SUM(o.sales) AS coffee_type_sales
    FROM gold.fact_orders AS o
    LEFT JOIN gold.dim_products AS p
        ON o.product_key = p.product_key
    GROUP BY
        p.coffee_type
),

CoffeeTypeContribution AS (
    SELECT
        coffee_type,
        coffee_type_sales,
        SUM(coffee_type_sales) OVER () AS total_sales
    FROM CoffeeTypeSales
)

SELECT
    coffee_type,
    coffee_type_sales,
    total_sales,

    ROUND(
        100.0 * coffee_type_sales
        / NULLIF(total_sales, 0),
        2
    ) AS sales_contribution_percentage

FROM CoffeeTypeContribution
ORDER BY
    sales_contribution_percentage DESC;


